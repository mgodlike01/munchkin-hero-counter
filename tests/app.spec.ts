test('production PWA reloads offline with saved progress and local fonts', async ({ page, context }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await page.evaluate(async () => { await navigator.serviceWorker.ready; await document.fonts.ready })
  await expect(page.getByText('Готово к офлайну', { exact: true })).toBeVisible()
  await setNumber(page, 'Бонусы', '12')
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByTestId('combat-power')).toHaveText('13')
  await expect(page.getByText('Без интернета', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Уровень: увеличить', exact: true }).click()
  await expect(page.getByTestId('combat-power')).toHaveText('14')
  expect(await page.evaluate(async () => { await document.fonts.ready; return document.fonts.check('600 16px "Manrope Variable"') })).toBe(true)
  const coldStart = await context.newPage()
  await coldStart.goto('/')
  await expect(coldStart.getByTestId('combat-power')).toHaveText('14')
  expect(await coldStart.locator('link[rel="apple-touch-icon"]').getAttribute('href')).toBe('/apple-touch-icon-hero-v2.png')
  for (const [path, size] of [['/apple-touch-icon-hero-v2.png', 180], ['/icons/hero-v2-192.png', 192], ['/icons/hero-v2-512.png', 512], ['/icons/hero-v2-maskable-512.png', 512]] as const) {
    const dimensions = await coldStart.evaluate(async (url) => {
      const icon = new Image()
      icon.src = url
      await icon.decode()
      return [icon.naturalWidth, icon.naturalHeight]
    }, path)
    expect(dimensions).toEqual([size, size])
  }
  await coldStart.evaluate(async () => {
    await document.fonts.load('600 16px "Manrope Variable"', 'Герой Hero')
    await document.fonts.load('600 16px "Cormorant Garamond"', 'Герой Hero')
    const loaded = await document.fonts.load('400 20px "Neucha"', 'Герой Hero')
    if (loaded.length < 2) throw new Error('Local Neucha Latin/Cyrillic fonts were not loaded offline')
  })
  await coldStart.close()
  expect(errors).toEqual([])
})

