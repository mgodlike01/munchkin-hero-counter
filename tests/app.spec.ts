test('a waiting service worker updates only on request and preserves progress', async ({ page }) => {
  const swPath = new URL('../dist/sw.js', import.meta.url)
  const original = await readFile(swPath, 'utf8')
  await page.goto('/')
  await page.evaluate(() => navigator.serviceWorker.ready)
  await setNumber(page, 'Уровень', '7')
  try {
    await writeFile(swPath, `${original}\n// update-check-${Date.now()}\n`)
    await page.evaluate(async () => { const r = await navigator.serviceWorker.ready; await r.update() })
    await expect(page.getByText('Прибыло обновление', { exact: true })).toBeVisible({ timeout: 15000 })
    await expect(page.getByTestId('combat-power')).toHaveText('7')
    await Promise.all([
      page.waitForEvent('domcontentloaded'),
      page.getByRole('button', { name: 'Обновить', exact: true }).click(),
    ])
    await expect(page.getByTestId('combat-power')).toHaveText('7')
    await expect(page.getByText('Прибыло обновление', { exact: true })).toBeHidden()
  } finally {
    await writeFile(swPath, original)
  }
})
