import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

const targets = ['level-increase', 'equipment-open', 'equipment-items', 'equipment-add', 'equipment-remove', 'confirm-action', 'equipment-close', 'settings-open', 'documentation-open']

async function number(page: Page, label: string, value: string) {
  const input = page.getByRole('spinbutton', { name: label, exact: true })
  await input.fill(value)
  await input.press('Enter')
}

for (const [width, height, theme] of [[320, 568, 'light'], [390, 844, 'dark'], [640, 360, 'dark']] as const) {
  test(`interactive tutorial preserves the hero at ${width}x${height} in ${theme} theme`, async ({ page }) => {
    const errors: string[] = []
    page.on('pageerror', (error) => errors.push(error.message))
    page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
    await page.setViewportSize({ width, height })
    await page.goto('/')
    await number(page, 'Уровень', '7')
    await number(page, 'Бонусы', '11')
    if (theme === 'dark') {
      await page.getByRole('button', { name: 'Открыть настройки' }).click()
      await page.getByRole('button', { name: 'Тёмная', exact: true }).click()
      await page.getByRole('button', { name: 'Закрыть: Настройки приключения' }).click()
    }
    const saved = await page.evaluate(() => localStorage.getItem('munchkin.hero.v1'))
    await page.getByRole('button', { name: 'Начать обучение', exact: true }).click()
    for (let index = 0; index < targets.length; index++) {
      const target = page.locator('.tour-target')
      await expect(target).toHaveAttribute('data-tour', targets[index])
      const coach = page.getByRole('region', { name: 'Подсказка обучения' })
      await expect(coach).toContainText(`Шаг ${index + 1} из ${targets.length}`)
      const box = await coach.boundingBox()
      const button = await target.boundingBox()
      expect(box!.x).toBeGreaterThanOrEqual(0)
      expect(box!.y).toBeGreaterThanOrEqual(0)
      expect(box!.x + box!.width).toBeLessThanOrEqual(width)
      expect(box!.y + box!.height).toBeLessThanOrEqual(height)
      const overlap = Math.max(0, Math.min(box!.x + box!.width, button!.x + button!.width) - Math.max(box!.x, button!.x))
        * Math.max(0, Math.min(box!.y + box!.height, button!.y + button!.height) - Math.max(box!.y, button!.y))
      expect(overlap).toBe(0)
      expect(await page.evaluate(() => localStorage.getItem('munchkin.hero.v1'))).toBe(saved)
      if (index === 0 || index === 3 || index === 5) await page.screenshot({ path: `test-results/tutorial-${width}-step-${index + 1}.png` })
      await target.click()
      if (index === 0) await expect(page.getByTestId('combat-power')).toHaveText('2')
      if (index === 3) await expect(page.getByRole('textbox', { name: 'Название: Доп. предмет 1', exact: true })).toBeVisible()
      if (index === 5) await expect(page.getByRole('textbox', { name: 'Название: Доп. предмет 1', exact: true })).toHaveCount(0)
    }
    await expect(page.getByRole('dialog', { name: 'Документация', exact: true })).toBeVisible()
    await expect(page.getByRole('dialog', { name: 'Документация', exact: true }).getByRole('status')).toContainText('Обучение пройдено')
    await expect(page.getByTestId('tutorial-layer')).toHaveCount(0)
    await page.getByRole('button', { name: 'Закрыть: Документация', exact: true }).click()
    await expect(page.getByTestId('combat-power')).toHaveText('18')
    expect(await page.evaluate(() => localStorage.getItem('munchkin.hero.v1'))).toBe(saved)
    expect(await page.evaluate(() => localStorage.getItem('munchkin.tutorial.v1'))).toBe('completed')
    expect(await page.evaluate(() => document.body.style.overflow)).not.toBe('hidden')
    await page.reload()
    await expect(page.getByRole('region', { name: 'Знакомство с приложением' })).toHaveCount(0)
    await expect(page.getByTestId('combat-power')).toHaveText('18')
    expect(errors).toEqual([])
  })
}

test('tutorial can be replayed, closed and interrupted by reload without changing equipped items', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Головняк: увеличить бонус', exact: true }).click()
  const saved = await page.evaluate(() => localStorage.getItem('munchkin.hero.v1'))
  await page.getByRole('button', { name: 'Позже', exact: true }).click()
  await page.getByRole('button', { name: 'Открыть настройки' }).click()
  await page.getByRole('button', { name: 'Обучение', exact: true }).click()
  await expect(page.locator('.tour-target')).toHaveAttribute('data-tour', 'level-increase')
  await page.getByRole('button', { name: 'Выйти из обучения', exact: true }).click()
  await expect(page.getByTestId('combat-power')).toHaveText('2')
  expect(await page.evaluate(() => localStorage.getItem('munchkin.hero.v1'))).toBe(saved)
  await page.getByRole('button', { name: 'Открыть настройки' }).click()
  await page.getByRole('button', { name: 'Обучение', exact: true }).click()
  await expect(page.locator('.tour-target')).toHaveAttribute('data-tour', 'level-increase')
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('tutorial-layer')).toHaveCount(0)
  await page.getByRole('button', { name: 'Открыть настройки' }).click()
  await page.getByRole('button', { name: 'Обучение', exact: true }).click()
  await expect(page.locator('.tour-target')).toHaveAttribute('data-tour', 'level-increase')
  await page.locator('.tour-target').click()
  await expect(page.locator('.tour-target')).toHaveAttribute('data-tour', 'equipment-open')
  await page.locator('.tour-target').click()
  await expect(page.getByRole('dialog', { name: 'Снаряжение героя' })).toBeVisible()
  await page.getByRole('dialog', { name: 'Снаряжение героя' }).evaluate((dialog) => dialog.dispatchEvent(new Event('cancel', { cancelable: true })))
  await expect(page.getByTestId('tutorial-layer')).toHaveCount(0)
  expect(await page.evaluate(() => document.body.style.overflow)).not.toBe('hidden')
  expect(await page.evaluate(() => localStorage.getItem('munchkin.hero.v1'))).toBe(saved)
  await page.getByRole('button', { name: 'Открыть настройки' }).click()
  await page.getByRole('button', { name: 'Обучение', exact: true }).click()
  await expect(page.locator('.tour-target')).toHaveAttribute('data-tour', 'level-increase')
  await page.locator('.tour-target').click()
  await expect(page.locator('.tour-target')).toHaveAttribute('data-tour', 'equipment-open')
  await page.reload()
  await expect(page.getByTestId('combat-power')).toHaveText('2')
  expect(await page.evaluate(() => localStorage.getItem('munchkin.hero.v1'))).toBe(saved)
  await expect(page.getByTestId('tutorial-layer')).toHaveCount(0)
})

test('documentation and training are available offline from settings', async ({ page, context }) => {
  await page.setViewportSize({ width: 320, height: 568 })
  await page.goto('/')
  await page.evaluate(() => navigator.serviceWorker.ready)
  await context.setOffline(true)
  await page.reload()
  await page.getByRole('button', { name: 'Открыть настройки' }).click()
  await page.getByRole('button', { name: 'Документация', exact: true }).click()
  const docs = page.getByRole('dialog', { name: 'Документация', exact: true })
  await expect(docs).toContainText('Справка доступна без интернета')
  await docs.locator('summary').filter({ hasText: 'Добавление, удаление и запас' }).click()
  await expect(docs.getByText(/Основные слоты.*не удаляются/)).toBeVisible()
  expect(await docs.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
  await docs.evaluate((element) => { element.scrollTop = 0 })
  await page.screenshot({ path: 'test-results/documentation-320.png' })
  await docs.getByRole('button', { name: 'Пройти обучение', exact: true }).click()
  await expect(page.locator('.tour-target')).toHaveAttribute('data-tour', 'level-increase')
  await page.getByRole('button', { name: 'Выйти из обучения', exact: true }).click()
  await expect(page.getByText('Без интернета', { exact: true })).toBeVisible()
})
